import json
import time
import os
from lib import snapshot, oscake_rewrite, _read, run, DNCTL_CONF, IPFW_RULES, SYSCTLS, CAKE_STATS
from lib.redact import Redactor, sysctl_names


def cake_entries(cfg):
    pipes = {p['uuid']: p.get('number', '?') for p in cfg['pipes']}
    lines = []
    for e in cfg['cake']:
        lines.append('pipe %s: enabled=%s diffserv=%s isolation=%s ecn=%s ack_filter=%s wash=%s ingress=%s '
                     'link=%s overhead=%s mpu=%s framing=%s memlimit=%s  # %s' % (
                         pipes.get(e.get('pipe'), 'missing'), e.get('enabled', ''), e.get('diffserv', ''),
                         e.get('isolation', ''), e.get('ecn', ''), e.get('ack_filter', ''), e.get('wash', ''),
                         e.get('ingress', ''), e.get('link', ''), e.get('overhead', ''), e.get('mpu', ''),
                         e.get('framing', ''), e.get('memlimit', ''), e.get('description', '')))
    general = cfg.get('cake_general') or {}
    if general:
        lines.insert(0, 'general: ' + ' '.join('%s=%s' % kv for kv in sorted(general.items())))
    return '\n'.join(lines)


def shaper_lines(text):
    """ the traffic shaping section of ipfw.rules (rules 60000 and up) """
    out = []
    for line in (text or '').splitlines():
        parts = line.split()
        if len(parts) > 1 and parts[0] == 'add' and parts[1].isdigit() and int(parts[1]) >= 60000:
            out.append(line)
    return '\n'.join(out)


def prio_marks():
    """ the priority rules (prio.py) with counters, and the addresses in their tables """
    rc, out, err = run(['/sbin/ipfw', '-S', 'show', '2000-2099'])
    lines = [x for x in out.splitlines() if ' set 7 ' in ' ' + x + ' ']
    if rc != 0 and not lines:
        return '' if 'not found' in err or not err.strip() else err.strip()
    for table in ('si_prio_interactive', 'si_prio_background'):
        rc, out, _ = run(['/sbin/ipfw', 'table', table, 'list'])
        if rc == 0 and out.strip():
            entries = [x.split()[0] for x in out.splitlines() if x.strip() and not x.startswith('-')]
            lines.append('table %s: %s' % (table, ' '.join(entries)))
    return '\n'.join(lines)


if __name__ == '__main__':
    t0 = time.monotonic()
    snap = snapshot()
    raw = snap['kernel']['raw']
    v = snap['versions']
    dnctl_conf = _read(DNCTL_CONF) or ''
    rewrite, rewrite_errors = oscake_rewrite(dnctl_conf) if snap.get('oscake') is not None else (None, [])
    sysctl_lines = raw.get('sysctl', '').strip()
    panels = [
        {'id': 'versions', 'title': 'Versions',
         'help': 'OPNsense, kernel, plugin and os-cake versions. Forum helpers ask for these first.',
         'text': '\n'.join('%s: %s' % (k, v[k]) for k in sorted(v) if v[k])},
        {'id': 'dnctl_conf', 'title': 'dnctl input generated by the shaper (%s)' % DNCTL_CONF,
         'help': 'The pipes and queues the core template wrote from Firewall: Shaper. rc.d/dnctl feeds this file '
                 'to dnctl on every Apply and firewall reload.',
         'text': dnctl_conf.strip()},
    ]
    if rewrite is not None:
        panels.append({'id': 'dnctl_cake', 'title': 'dnctl input after os-cake (reconstructed)',
                       'help': 'os-cake\'s wrapper replaces "type ..." with "type cake <options>" on pipes that have '
                               'an enabled CAKE entry, then loads it with its CAKE-capable dnctl. Rebuilt here from '
                               'os-cake\'s own settings code; os-cake does not save the file.',
                       'text': rewrite.strip() + ('\n# ' + '\n# '.join(rewrite_errors) if rewrite_errors else '')})
        panels.append({'id': 'cake_entries', 'title': 'os-cake entries (config.xml)',
                       'help': 'The CAKE settings per pipe, as saved on Firewall: Shaper: CAKE.', 'descr': True,
                       'text': cake_entries(snap['config'])})
    panels += [
        {'id': 'ipfw_rules', 'title': 'Shaper rules generated (%s, rules 60000+)' % IPFW_RULES,
         'help': 'Each enabled shaper rule becomes one ipfw rule, numbered 60000 + its position. The first match '
                 'wins.', 'descr': True, 'text': shaper_lines(_read(IPFW_RULES))},
        {'id': 'prio_marks', 'title': 'Priority marks loaded (ipfw set 7, rules 2000-2099)',
         'help': 'Shaper Insight\'s own rules: they set the DSCP mark that picks the CAKE tin, before the shaper '
                 'rules above send the packet to its pipe. Empty when no priority is set.', 'descr': True,
         'text': prio_marks()},
        {'id': 'ipfw_show', 'title': 'Shaper rules loaded, with counters (ipfw show 60000-65535)',
         'help': 'Packets and bytes per rule since the last reload. A rule with 0 packets never matched.', 'descr': True,
         'text': (raw.get('ipfw') or '').strip() or raw.get('ipfw_error', '')},
        {'id': 'dnctl_show', 'title': 'Kernel objects (dnctl queue show; sched show)',
         'help': 'What the kernel really runs. "type CAKE" proves CAKE is active on that pipe; the line under it '
                 'lists its options when cake-kmod\'s dnctl is installed.',
         'text': (raw.get('dnctl') or '').strip() or raw.get('dnctl_error', '')},
        {'id': 'cake_stats', 'title': 'CAKE counters (sysctl net.inet.ip.dummynet.cake.stats)',
         'help': 'One line per pipe, instance and tin. Delays are in microseconds.',
         'text': (raw.get('cake_stats') or '').strip() or '(not available: no CAKE scheduler loaded, or cake-kmod '
                                                          'older than 1.3)'},
        {'id': 'tunables', 'title': 'Timer and forwarding settings',
         'help': 'kern.hz sets the shaper\'s timing; share_forward lets policy-routed traffic reach the shaper.',
         'text': sysctl_lines},
        {'id': 'modules', 'title': 'Kernel modules (kldstat)',
         'help': 'dummynet.ko is the shaper; dn_cake.ko (or dummynet_st.ko) adds CAKE.',
         'text': '\n'.join(line for line in (raw.get('kldstat') or '').splitlines()
                           if line.startswith('Id') or any(m in line for m in ('dummynet', 'dn_cake', 'ipfw')))},
    ]
    # exact names that are safe to show: sysctl names the kernel itself printed, the files
    # this script names, the kernel modules kldstat listed. Nothing is allowed by pattern.
    allow = set(SYSCTLS) | {CAKE_STATS} | sysctl_names(sysctl_lines) | sysctl_names(raw.get('cake_stats', ''))
    allow |= {os.path.basename(f) for f in (DNCTL_CONF, IPFW_RULES)}
    allow |= set(snap['kernel'].get('kld', {}).get('modules', []))
    red = Redactor(allow)
    for p in panels:
        # comment redaction for every panel, not opt-in: a panel added later, or text a template
        # writes after "#", is covered without anyone remembering to ask (review S12)
        p.pop('descr', None)
        p['redacted'] = red.text(p['text'], descriptions=True)
    print(json.dumps({'panels': panels, 'redactions': red.counts(), 'generated': snap['generated'],
                      'cached': snap['cached'], 'elapsed_ms': round((time.monotonic() - t0) * 1000, 1)}))
